"""
Missing-modality dataset for GBMLGG. SAME interface as dataset_mm (KIRC) so the
existing runners work unchanged:  load_gene_dict(), load_fold_config(), CONFIGS.

Per patient:
  X_img  (1536,) : pooled UNI2-h (patient-level, from gbmlgg_uni2h_patient_1536d.pkl)
  X_gene (256,)  : BulkRNABert embedding
  img_present    : 1.0 if WSI cell present in CSV, else 0.0 (blanked)
  gene_present   : 1.0 if Omics cell present, else 0.0 (blanked)
  t (time)       : CSV 'Event'  (Survival months; days, internally consistent)
  e (event)      : CSV 'Status' (1 = event/death = 1-censored; Paper-1 convention)

Paired set = 592 (image ∩ gene ∩ survival). Splits generated by
generate_gbmlgg_splits.py. Missingness = mask (val always complete).
"""
import os
import pickle
import numpy as np
import pandas as pd

GBMLGG_SPLITS = "/home/sbarua/Region_based_segmentation/missing_modality/data_gbmlgg/splits"
IMG_PKL = "/home/sbarua/Region_based_segmentation/pathgptomic_bulkrnabert_patient_level/bulkrnabert_data/gbmlgg_uni2h_patient_1536d.pkl"
BULK_NPZ = "/home/sbarua/Region_based_segmentation/pathgptomic_bulkrnabert_patient_level/bulkrnabert_data/gbmlgg_bulkrnabert_256d.npz"

CONFIGS = ["W0_O0", "W0_O60", "W20_O40", "W30_O30", "W40_O20", "W60_O0"]

_img_dict = None


def load_gene_dict():
    z = np.load(BULK_NPZ, allow_pickle=True)
    emb = z["embeddings"]
    assert emb.shape[1] == 256, f"gene dim {emb.shape[1]} != 256"
    return {str(p): emb[i].astype(np.float32) for i, p in enumerate(z["patient_ids"])}


def _image_dict():
    global _img_dict
    if _img_dict is None:
        df = pickle.load(open(IMG_PKL, "rb"))
        assert df.shape[1] == 1536, f"image dim {df.shape[1]} != 1536"
        _img_dict = {str(pid): df.loc[pid].to_numpy(np.float32) for pid in df.index}
    return _img_dict


def _assemble(sub: pd.DataFrame, gene_dict: dict) -> dict:
    imgd = _image_dict()
    n = len(sub)
    X_img = np.zeros((n, 1536), np.float32)
    X_gene = np.zeros((n, 256), np.float32)
    img_present = np.zeros(n, np.float32)
    gene_present = np.zeros(n, np.float32)
    t = np.zeros(n, np.float32); e = np.zeros(n, np.float32)
    ids = []
    for i, (_, row) in enumerate(sub.iterrows()):
        pid = str(row["ID"])
        X_img[i] = imgd[pid]
        X_gene[i] = gene_dict[pid]
        img_present[i] = 0.0 if pd.isna(row["WSI"]) else 1.0
        gene_present[i] = 0.0 if pd.isna(row["Omics"]) else 1.0
        t[i] = float(row["Event"]); e[i] = float(row["Status"])
        ids.append(pid)
    return dict(X_img=X_img, X_gene=X_gene, img_present=img_present,
                gene_present=gene_present, t=t, e=e, ids=ids)


def load_fold_config(fold: int, cfg: str, gene_dict: dict) -> dict:
    csv = os.path.join(GBMLGG_SPLITS, f"GBMLGG_fold_{fold}_{cfg}.csv")
    df = pd.read_csv(csv)
    return {
        "train": _assemble(df[df["Split"] == "train"].reset_index(drop=True), gene_dict),
        "val":   _assemble(df[df["Split"] == "val"].reset_index(drop=True),   gene_dict),
    }


if __name__ == "__main__":
    gd = load_gene_dict()
    for cfg in ["W0_O0", "W20_O40"]:
        d = load_fold_config(0, cfg, gd)
        tr, va = d["train"], d["val"]
        print(f"[{cfg}] train n={len(tr['t'])} val n={len(va['t'])} | "
              f"img-miss={int((tr['img_present']==0).sum())} gene-miss={int((tr['gene_present']==0).sum())} "
              f"both-present={int(((tr['img_present']==1)&(tr['gene_present']==1)).sum())}")
        print(f"       X_img{tr['X_img'].shape} X_gene{tr['X_gene'].shape} "
              f"events(tr)={int(tr['e'].sum())} val-complete={bool((va['img_present']==1).all() and (va['gene_present']==1).all())}")
    print("SMOKE OK")
